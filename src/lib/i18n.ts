let lang: Lang = "es";

export function resolveLang(s?: string | null): Lang {
  if (s === "es" || s === "en" || s === "pt") return s;
  const n = navigator.language.slice(0, 2).toLowerCase();
  return n === "en" || n === "pt" ? n : "es";
}

export function setLang(s?: string | null) {
  lang = resolveLang(s);
  document.documentElement.lang = lang;
}

export function t(src: string, ...args: (string | number)[]): string {
  const dict = lang === "en" ? EN : lang === "pt" ? PT : undefined;
  let out = dict?.[src] ?? src;
  args.forEach((a, i) => { out = out.split(`{${i}}`).join(String(a)); });
  return out;
}

/** Traduce el HTML estático: data-i18n (texto), data-i18n-title, data-i18n-placeholder. El valor es el texto en español. */
export function applyStatic(root: ParentNode = document) {
  root.querySelectorAll<HTMLElement>("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n!); });
  root.querySelectorAll<HTMLElement>("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle!); });
  root.querySelectorAll<HTMLInputElement>("[data-i18n-placeholder]").forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder!); });
}
